function puppetCostText (cost) {
  const mats = Object.entries(cost.materials).map(([n, c]) => `${itemIcon(n)}${n}×${c}`)
  if (Number(cost.money) > 0) mats.push(`💰灵石×${Number(cost.money).toLocaleString()}`)
  return mats.join('、')
}

async function replyLines (e, title, lines) {
  const full = [title, ...lines]
  let img = null
  try { img = await textToImg(full.join('\n')) } catch (err) { }
  if (img) e.reply(img)
  else e.reply(full.join('\n'))
}

